  var DEFAULT_LOCALE = 'zh-CN';
  var current = DEFAULT_LOCALE;

  function has(table, key) {
    return Object.prototype.hasOwnProperty.call(table, key);
  }

  function detectLocale() {
    var names = Object.keys(MESSAGES);
    try {
      var lang = String((root.navigator && root.navigator.languages && root.navigator.languages[0]) ||
        (root.navigator && root.navigator.language) || '');
      if (lang) {
        var lower = lang.toLowerCase();
        for (var i = 0; i < names.length; i += 1) {
          if (lower.indexOf(names[i].toLowerCase()) === 0) { return names[i]; }
        }
        // 语言族匹配：暂只有一份中文，zh-TW/zh-HK 等先回落中文，不出现英文默认
        if (lower.indexOf('zh') === 0) { return DEFAULT_LOCALE; }
      }
    } catch (err) { /* 桩环境或受限浏览器：继续用默认语言 */ }
    try {
      var stored = root.localStorage && root.localStorage.getItem('a2n.lang');
      if (stored && has(MESSAGES, stored)) { return stored; }
    } catch (err) { /* 同上 */ }
    return DEFAULT_LOCALE;
  }

  function table() {
    return MESSAGES[current] || MESSAGES[DEFAULT_LOCALE] || {};
  }

  function text(key) {
    var t0 = table();
    if (has(t0, key)) { return t0[key]; }
    if (current !== DEFAULT_LOCALE && has(MESSAGES[DEFAULT_LOCALE], key)) {
      return MESSAGES[DEFAULT_LOCALE][key];
    }
    return null;
  }

  function t(key, vars) {
    var value = text(key);
    if (value === null) { return key; }
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        value = String(value).split('{' + name + '}').join(String(vars[name]));
      });
    }
    return value;
  }

  function start() {
    current = detectLocale();
    try {
      if (typeof document !== 'undefined' && document.documentElement &&
          typeof document.documentElement.setAttribute === 'function') {
        document.documentElement.setAttribute('lang', current);
      }
    } catch (err) { /* 只读环境：跳过 */ }
  }

  return {
    messages: MESSAGES,
    locale: function () { return current; },
    text: text,
    t: t,
    setLocale: function (name) {
      if (!has(MESSAGES, name)) { return false; }
      current = name;
      try {
        if (root.localStorage && root.localStorage.setItem) {
          root.localStorage.setItem('a2n.lang', name);
        }
      } catch (err) { /* 无存储时仅内存生效 */ }
      start();
      return true;
    },
    start: start
  };
