/* Read-only check of the real installed desktop console; no test trades. */
const {chromium}=require('playwright-core');
const assert=require('assert'),crypto=require('crypto'),fs=require('fs'),path=require('path'),http=require('http');
const root=path.resolve(__dirname,'..'),base='http://127.0.0.1:8771';
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-proxy-server']});
 const page=await browser.newPage(),errors=[],checks=[];
 const check=(name,value)=>{assert(value,name);checks.push(name);console.log('PASS '+name)};
 page.on('pageerror',e=>errors.push(e.message));
 try{
  const unauthorized=await new Promise((resolve,reject)=>{
   http.get(base+'/v1/runtime',res=>{let body='';res.on('data',chunk=>body+=chunk);res.on('end',()=>{try{const row=JSON.parse(body);resolve({status:res.statusCode,error:row.error,selection:row.selection??null,task_quality:row.task_quality??null,calibration:row.calibration??null})}catch(e){reject(e)}})}).on('error',reject);
  });
  check('unauthenticated runtime is rejected rather than treated as missing modules',unauthorized.status===401);
  await page.goto(base+'/console');
  await page.waitForFunction(()=>window.a2nSelection&&window.A2NTradeUI&&snapshot?.selection?.enabled);
  const runtime=await page.evaluate(async()=>{
   const r=await request('/v1/runtime');
   return {node_did:r.node_did,product_runtime:r.product_runtime,selection:r.selection,task_quality:r.task_quality,calibration:r.calibration};
  });
  const sha=crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'artifacts/A2N.exe'))).digest('hex');
  check('8771 executes the exact current installed bundle',runtime.product_runtime.mode==='BUNDLED'&&runtime.product_runtime.executable_sha256===sha);
  check('selection is enabled on the actual installed node',runtime.selection?.enabled===true);
  check('task quality is enabled on the actual installed node',runtime.task_quality?.enabled===true);
  check('calibration is enabled on the actual installed node',runtime.calibration?.enabled===true);
  check('actual bundle exposes personal selection and independent review controls',await page.locator('#selectionDemand').count()===1&&await page.locator('#qaIndependentKind').count()===1);
  check('actual feedback copy matches independent reputation and selection behavior',(await page.locator('#account').textContent()).includes('聚合信誉和本机推荐另外展示'));
  check('actual installed console has no JavaScript errors',errors.length===0);
  fs.writeFileSync(path.join(root,'artifacts/installed-node-modules-2026-10-09.json'),JSON.stringify({observed_at:new Date().toISOString(),passed:true,base,checks,unauthorized,runtime,errors},null,2));
 }finally{await browser.close()}
})().catch(error=>{console.error(error.message);process.exitCode=1});
